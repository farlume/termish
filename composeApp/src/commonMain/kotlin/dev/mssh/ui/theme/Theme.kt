/** 终端配色主题（ARGB 打包 Long）。 */
data class TerminalTheme(
    val name: String,
    val background: Long,
    val foreground: Long,
    val cursor: Long,
    val selection: Long,
    /** 16 个 ANSI 基础色。 */
    val ansi: List<Long>,
) {
    fun background(): Color = Color(background)
    fun foreground(): Color = Color(foreground)
    fun cursor(): Color = Color(cursor)
    fun selection(): Color = Color(selection)
    fun ansi(i: Int): Color = Color(ansi[i])
}

private fun argb(a: Int, r: Int, g: Int, b: Int): Long =
    ((a.toLong() and 0xff) shl 24) or ((r.toLong() and 0xff) shl 16) or ((g.toLong() and 0xff) shl 8) or (b.toLong() and 0xff)

