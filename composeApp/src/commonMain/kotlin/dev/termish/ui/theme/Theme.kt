@Composable
fun TermishTheme(mode: ThemeMode, content: @Composable () -> Unit) {
    val scheme = when (mode) {
        ThemeMode.LIGHT -> LightColors
        else -> DarkColors
    }
    MaterialTheme(colorScheme = scheme, content = content)
}
